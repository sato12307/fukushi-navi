// toei-top-card.mjs — トップページ（index.html・手書き）にある /toei/ の案内カードの数え方。
//
// ★なぜ1か所にするか（2026-10-11）
//   カードの件数を書き換える scripts/toei-nerai.mjs と、KV に入れる前に件数を突き合わせる
//   scripts/toei-put-pack.mjs の両方が「トップに /toei/ のカードがあるか」を問う。
//   2か所に書くと片方だけずれる。[[same-question-two-implementations]]
//
// ★カードが無いのは正常（2026-10-08 から）
//   トップを読まれている順に並べ直したとき（4404d0d4）、/toei/ はカードから外れ、
//   件数の無い文字のリンク（「毎回すいている申込先（…）：都営住宅／…」）になった。
//   書き換えるもの・突き合わせるものが無いだけで、壊れているのではない。
//   ★ここからカードをトップへ戻すことはしない。どの面をカードにするかは、読まれ方を見て決めている。
// ─────────────────────────────────────────────────────────────────────────────

// <a> の開きタグのうち、class に card を持ち、/toei/ を指すものの数。
// 件数を書き換える正規表現（toei-nerai.mjs）より広く取る。カードの形が変わって書き換えが当たらないときに、
// 「カードは無い」と読んで古い件数のまま出すのではなく、止められるように。文字のリンクは class="card" が無いので数えない。
export const toeiTopCards = (html) => (html.match(/<a\s[^>]*>/g) || [])
  .filter((tag) => /\sclass="(?:[^"]*\s)?card(?:\s[^"]*)?"/.test(tag) && /\shref="[^"]*\btoei\/(?:index\.html)?"/.test(tag)).length
