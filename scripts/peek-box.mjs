// peek-box.mjs — 「実物の冒頭をそのまま出す」抜粋の枠。
//
// ★なぜ別ファイルにするか（2026-09-18）
//   もともと offer-block.mjs の中に置いていたが、/toei/ の売り場ページ（toei-nerai.mjs が
//   作る）からも使いたくなった。offer-block.mjs は toei-peek.mjs（toei-nerai.mjs が
//   自動生成する）を読み込むので、toei-nerai.mjs から offer-block.mjs を読むと
//   「自分が書くファイルを、書く前に読む」形になる。∴ 依存の無い部品として切り出す。
//
// ★かすませるのは「ここで切れている」という印であって、隠しているのではない。
//   かすんだ先の本文はHTMLに入れない（ソースを見ても続きは出てこない）。
//   [[paywall-teaser-note-style]]
// ─────────────────────────────────────────────────────────────────────────────
export const peekBox = (label, inner) => `  <p class="peek-lead">説明だけでは分からないと思うので、<strong>実物の冒頭をそのまま</strong>出します。宣伝用に書き直したものではありません。</p>
  <div class="peek" aria-label="${label}">
${inner}
  </div>
  <p class="peekcut"><span>抜粋はここまで</span></p>
  <p class="fine">かすんでいるのは「ここで切れている」という印です。<strong>この先の本文はこのページに入っていません</strong>（ソースを見ても続きは出てきません）。</p>`
